"use client";

import { useActionState } from "react";
import {
  startTotpEnrollment,
  verifyTotpEnrollment,
} from "@/app/(cockpit)/settings/security/actions";
import { FormMessage } from "@/components/form-message";
import { IDLE_STATE } from "@/lib/action-state";

export function TotpEnrollment() {
  const [started, start, starting] = useActionState(startTotpEnrollment, IDLE_STATE);
  const [verified, verify, verifying] = useActionState(verifyTotpEnrollment, IDLE_STATE);
  const enrolment = started.status === "success" ? started.data : undefined;

  if (verified.status === "success") return <FormMessage state={verified} />;

  if (!enrolment) {
    return (
      <form action={start} className="space-y-2">
        <button
          type="submit"
          disabled={starting}
          className="rounded-md bg-nx-teal px-3 py-1.5 text-sm font-semibold text-nx-bg disabled:opacity-60"
        >
          Set up an authenticator app
        </button>
        <FormMessage state={started} />
      </form>
    );
  }

  return (
    <form action={verify} className="max-w-md space-y-4">
      <ol className="list-decimal space-y-2 pl-5 text-sm">
        <li>
          Scan this QR code with an authenticator app (1Password, Authy, Google Authenticator…).
        </li>
        <li>Enter the 6-digit code it shows.</li>
      </ol>
      {/* The QR code is an SVG data URL generated by Supabase Auth. */}
      {/* eslint-disable-next-line @next/next/no-img-element */}
      <img
        src={enrolment.qrCode}
        alt="QR code for your authenticator app"
        width={180}
        height={180}
        className="rounded bg-white p-2"
      />
      <p className="text-xs text-nx-muted">
        Can&apos;t scan? Enter this key manually:{" "}
        <code data-testid="totp-secret" className="break-all font-mono text-nx-text">
          {enrolment.secret}
        </code>
      </p>
      <input type="hidden" name="factorId" value={enrolment.factorId} />
      <label htmlFor="totp-code" className="block text-sm font-medium">
        Authentication code
      </label>
      <input
        id="totp-code"
        name="code"
        inputMode="numeric"
        autoComplete="one-time-code"
        pattern="\d{6}"
        maxLength={6}
        required
        className="w-40 rounded-md border border-nx-border bg-nx-bg px-3 py-2 font-mono text-lg tracking-widest"
      />
      <div>
        <button
          type="submit"
          disabled={verifying}
          className="rounded-md bg-nx-teal px-3 py-1.5 text-sm font-semibold text-nx-bg disabled:opacity-60"
        >
          Turn on two-factor authentication
        </button>
      </div>
      <FormMessage state={verified} />
    </form>
  );
}
