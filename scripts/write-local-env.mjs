// Writes apps/web/.env.local from the running local Supabase (`supabase start` first).
// Usage: node scripts/write-local-env.mjs [owner-email]
// The local keys are Supabase's published development defaults, not real secrets.
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const ownerEmail = process.argv[2] ?? "owner@nexus.test";
const status = Object.fromEntries(
  execSync("supabase status -o env", { encoding: "utf8" })
    .split(/\r?\n/)
    .map((line) => line.match(/^([A-Z_]+)="?(.*?)"?$/))
    .filter(Boolean)
    .map((match) => [match[1], match[2]]),
);

const lines = [
  "# Generated by scripts/write-local-env.mjs for local development. Do not commit.",
  `NEXT_PUBLIC_SUPABASE_URL=${status.API_URL}`,
  `NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${status.PUBLISHABLE_KEY}`,
  `SUPABASE_SECRET_KEY=${status.SECRET_KEY}`,
  `NEXUS_OWNER_EMAIL=${ownerEmail}`,
  "NEXUS_MODEL_FIXTURE=1",
  "NEXUS_GLOBAL_MONTHLY_BUDGET_USD=20",
  `MAILPIT_URL=${status.MAILPIT_URL ?? status.INBUCKET_URL}`,
];

for (const required of ["API_URL", "PUBLISHABLE_KEY", "SECRET_KEY"]) {
  if (!status[required])
    throw new Error(`supabase status did not report ${required}; is it running?`);
}

writeFileSync("apps/web/.env.local", lines.join("\n") + "\n");
console.log(`Wrote apps/web/.env.local (owner: ${ownerEmail})`);
